function mergeLocale(file, lang) {
  const target = path.join(root, file)
  const json = JSON.parse(fs.readFileSync(target, 'utf8'))
  json.freight = {
    ...json.freight,
    fields: { ...extract[lang].fields, ...fieldOverrides[lang] },
    sections: extract[lang].sections,
    modules: extract[lang].modules,
    tables: extract[lang].tables,
    moduleActions: extract[lang].moduleActions,
    ui: ui[lang],
    jobSections: jobSections[lang],
    kpis: kpis[lang],
    alerts: alerts[lang],
  }
  fs.writeFileSync(target, `${JSON.stringify(json, null, 2)}\n`)
}

mergeLocale('i18n/locales/en.json', 'en')
mergeLocale('i18n/locales/km.json', 'km')
