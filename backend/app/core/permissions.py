# --- Matrix page permissions (Roles & Permissions screen) --------------------
# Every page exposes the actions its API actually supports. These codes are what
# the role matrix stores; ``PAGE_PERMISSION_SOURCE_CODES`` maps them onto the
# source/API permissions they imply so a page grant also enables the matching
# API calls.
def _matrix(prefix: str, actions: tuple[str, ...]) -> tuple[tuple[str, str, str], ...]:
    return tuple((f"{prefix}.{action}", prefix, action) for action in actions)


