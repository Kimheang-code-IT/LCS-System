# Invert the page mapping once so a stored source permission still reveals the
# pages it used to unlock (roles created before the matrix existed).
def _invert_page_sources(mapping: dict[str, tuple[str, ...]]) -> dict[str, tuple[str, ...]]:
    result: dict[str, set[str]] = {}
    for page, sources in mapping.items():
        for source in sources:
            result.setdefault(source, set()).add(page)
    return {code: tuple(sorted(pages)) for code, pages in result.items()}


