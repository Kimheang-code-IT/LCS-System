def _dedupe_catalog(catalog: tuple[tuple[str, str, str], ...]) -> tuple[tuple[str, str, str], ...]:
    seen: set[str] = set()
    unique: list[tuple[str, str, str]] = []
    for item in catalog:
        if item[0] in seen:
            continue
        seen.add(item[0])
        unique.append(item)
    return tuple(unique)


